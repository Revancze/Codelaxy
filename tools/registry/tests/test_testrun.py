NS = "http://microsoft.com/schemas/VisualStudio/TeamTest/2010"


def trx(results, start="2026-11-01T16:09:37.6677643+01:00", finish="2026-11-01T16:12:09.0855674+01:00", summary="Completed", bom=False, extra=""):
    rows = "".join(f'<UnitTestResult executionId="e{i}" testId="t{i}" testName="{n}" outcome="{o}" duration="00:00:00.001" />' for i, (n, o) in enumerate(results))
    xml = (f'<?xml version="1.0" encoding="utf-8"?><TestRun id="x" xmlns="{NS}"><Times creation="{start}" queuing="{start}" start="{start}" finish="{finish}" />'
           f'<Results>{rows}</Results>{extra}<ResultSummary outcome="{summary}"><Counters total="{len(results)}" executed="{len(results)}" /></ResultSummary></TestRun>')
    return ("\ufeff" + xml if bom else xml).encode("utf-8")


