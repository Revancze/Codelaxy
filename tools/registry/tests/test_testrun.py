        self.assertTrue(w.truncated and l.truncated)
        t = testrun.parse_trx((TESTRUN / REAL["trx_win"]).read_bytes())
        o = testrun.observation(PILOT, t, w)
        self.assertEqual((o["outcome"], o["guard"]), ("UNVERIFIED", "NOT_LISTED_TRUNCATED_LIST"))

